// Parses a map definition into a MapGrid:
// { key, name, modes, w, h, tiles: Uint8Array(w*h), spawns: [[{x,y}...] team 0, [...] team 1] or
//   [[{x,y}...]] for Showdown (one list), mine: {x,y}|null, obj: {x,y}|null,
//   goals: [{team, x0, y0, x1, y1}] (team = the team that DEFENDS it), pads: [{x,y,tx,ty}] }
// All points are tile centres in world units (tiles).
function parseMap(key) {
  const def = MAPS[key];
  if (!def) throw new Error('Unknown map ' + key);
  let rows = def.rows.slice();
  const w = rows[0].length;
  for (const r of rows) if (r.length !== w) throw new Error(`Map ${key}: row width ${r.length} != ${w}: ${r}`);
  if (!def.full) {
    const top = rows.slice(0, rows.length - 1);
    const mirrored = top.slice().reverse().map((r) => r.split('').map((c) => MIRROR_SWAP[c] || c).join(''));
    rows = rows.concat(mirrored);
  }
  const h = rows.length;
  const tiles = new Uint8Array(w * h);
  const spawns = def.full ? [[]] : [[], []];
  const goals = [];
  const goalTiles = { Y: [], Z: [] };
  let mine = null, obj = null;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const c = rows[y][x];
      if (!(c in MAP_CHARS)) throw new Error(`Map ${key}: unknown char '${c}' at ${x},${y}`);
      tiles[y * w + x] = MAP_CHARS[c];
      const p = { x: x + 0.5, y: y + 0.5 };
      if (c === '1') spawns[0].push(p);
      else if (c === '2') spawns[1].push(p);
      else if (c === 'S') spawns[0].push(p);
      else if (c === 'G') mine = p;
      else if (c === 'O') obj = p;
      else if (c === 'Y' || c === 'Z') goalTiles[c].push([x, y]);
    }
  }
  for (const [c, team] of [['Y', 0], ['Z', 1]]) {
    const t = goalTiles[c];
    if (!t.length) continue;
    let x0 = 1e9, y0 = 1e9, x1 = -1e9, y1 = -1e9;
    for (const [x, y] of t) { x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x + 1); y1 = Math.max(y1, y + 1); }
    goals.push({ team, x0, y0, x1, y1 });
  }
  const pads = (def.pads || []).map(([x, y, tx, ty]) => ({ x: x + 0.5, y: y + 0.5, tx: tx + 0.5, ty: ty + 0.5 }));
  return { key, name: def.name, modes: def.modes, w, h, tiles, spawns, mine, obj, goals, pads };
}

// Copy of a MapGrid with its own tiles (the sim breaks walls, so every match needs its own copy).
function cloneMap(m) {
  return Object.assign({}, m, { tiles: new Uint8Array(m.tiles) });
}
